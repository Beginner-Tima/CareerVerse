/**
 * Широкий каталог профессий.
 *
 * Зачем он такой большой. Модель отвечает строго из каталога — иначе разъедутся
 * проба, план и письмо родителям, которые обязаны называть одну и ту же
 * профессию. Значит длина каталога и есть потолок теста: с шестью вариантами
 * подросток с интересом к праву, к сцене или к работе руками получал ближайшее
 * похожее и справедливо считал это натяжкой. Здесь около сотни направлений,
 * включая те, куда идут через колледж, а не через вуз.
 *
 * Цифр рынка труда здесь нет, и это решение, а не недоделка.
 *
 * Своей медианы у каждой профессии не существует в опубликованном виде:
 * обследование Бюро нацстатистики даёт укрупнённые категории работников, а не
 * профессии, а открытый API вакансий hh закрыт — `/vacancies` отвечает 403 без
 * зарегистрированного приложения. Единственное, что доступно, — медианы по 26
 * профобластям hh.kz. Подставлять их каждой профессии внутри области мы
 * пробовали и отказались: у всех айтишников выходила одна цифра, у всех
 * медиков другая, и на экране это выглядело как данные о профессии, хотя было
 * данными об отрасли.
 *
 * Поэтому цифры остались только у шести профессий, где они собраны поимённо, а
 * остальным экран результата честно говорит, что данных нет. Пустая ячейка,
 * про которую сказано «у нас этого нет», стоит дороже заполненной, про которую
 * непонятно, откуда она взялась.
 *
 * Идентификаторы короткие и читаемые, а не UUID, и это не про красоту:
 * модель обязана скопировать id дословно, и промах по 36 символам при сотне
 * вариантов давал бы 409 в момент выдачи результата. Дополнительно id зажат
 * перечислением в схеме ответа — см. `matchSchema` в src/ai/schemas.ts.
 *
 * Казахские названия нуждаются в вычитке носителем: часть терминов —
 * общепринятые заимствования, часть переведена по словарю.
 */
