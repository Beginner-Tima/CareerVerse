/**
 * Широкий каталог профессий.
 *
 * Зачем он такой большой. Модель отвечает строго из каталога — иначе разъедутся
 * проба, план и письмо родителям, которые обязаны называть одну и ту же
 * профессию. Значит длина каталога и есть потолок теста: с шестью вариантами
 * подросток с интересом к праву, к сцене или к работе руками получал ближайшее
 * похожее и справедливо считал это натяжкой. Здесь около сотни направлений,
 * включая те, куда идут через колледж, а не через вуз.
 *
 * Цифры рынка труда есть у восемнадцати профессий — ровно у тех, по которым их
 * удалось собрать поимённо.
 *
 * Открытый API вакансий hh закрыт: `/vacancies` отвечает 403 без
 * зарегистрированного приложения. Но HTML-страница поиска отдаётся без ключа, и
 * по ней берётся медиана — бисекцией по фильтру «доход не менее X»: сужаем
 * `only_with_salary=true&salary=X`, пока выше порога не останется половина. Это
 * медиана по профессии, а не по отрасли, и её можно повторить при
 * спрашивающем — запрос и знаменатель записаны в `source` каждой записи.
 *
 * Числа вакансий в базу не идут, хотя и посчитаны. Поиск по строке нечёткий, и
 * счётчик от этого раздувается: «менеджер по продажам» выдаёт 6625 вакансий по
 * стране, «бухгалтер» — 2145, потому что запрос цепляет всё, где эти слова
 * вообще встретились. Медиану перекос смещает умеренно — вилки съезжают в одну
 * сторону, — а вот само число читается как измерение рынка, которым оно не
 * является. Поэтому в записи осталось только то, что переживает нечёткий поиск:
 * медиана и порядок регионов по объёму. Исходные счётчики видны в вызовах `hh`
 * ниже — они нужны, чтобы этот порядок посчитать, и чтобы через месяц было с
 * чем сверить новую выгрузку.
 *
 * Чего медиана не значит. Фильтр hh засчитывает вилку по верхней границе,
 * поэтому она смещена вверх. Нечёткий поиск добавляет к этому своё: «повар»
 * ловит шеф-повара и вахту, «автомеханик» — спецтехнику, отчего у рабочих
 * специальностей выходит больше ожидаемого. Зарплату скрывают от 13%
 * работодателей (медсестра) до 65% (frontend), и считается только по открытым.
 * И главное: hh — одна площадка с перекосом в города и частный сектор. Учителей
 * начальных классов на ней 105 на всю страну, а на enbek.kz в образовании
 * 12 959 вакансий, потому что бюджетные школы нанимают мимо hh. Значит 415 000 ₸
 * у учителя — это про частный центр в Алматы, а не про гос. школу.
 *
 * Почему не всем девяноста шести. Областные медианы hh по 26 профобластям
 * подставлять каждой профессии внутри области мы пробовали и отказались: у всех
 * айтишников выходила одна цифра, у всех медиков другая, и на экране это
 * выглядело как данные о профессии, хотя было данными об отрасли. Остальным
 * экран результата по-прежнему честно говорит, что данных нет. Пустая ячейка,
 * про которую сказано «у нас этого нет», стоит дороже заполненной, про которую
 * непонятно, откуда она взялась. По той же причине пуст инженер-нефтяник: hh на
 * такой запрос не находит ничего, и подставить ему результат похожего запроса
 * значит выдумать цифру.
 *
 * Идентификаторы короткие и читаемые, а не UUID, и это не про красоту:
 * модель обязана скопировать id дословно, и промах по 36 символам при сотне
 * вариантов давал бы 409 в момент выдачи результата. Дополнительно id зажат
 * перечислением в схеме ответа — см. `matchSchema` в src/ai/schemas.ts.
 *
 * Казахские названия нуждаются в вычитке носителем: часть терминов —
 * общепринятые заимствования, часть переведена по словарю.
 */
/**
 * Поля совпадают с моделью LaborMarketData: сид кладёт объект в базу как есть.
 * Из модели сюда не переехали `vacancyCount` и `demandTrend` — почему, в шапке.
 */
export interface CatalogMarket {
  medianSalaryKzt: number;
  regions: string[];
  source: string;
  collectedAt: Date;
}

export interface CatalogEntry {
  id: string;
  title: string;
  titleKk: string;
  description: string;
  /** Есть у восемнадцати профессий из девяноста шести — почему, см. шапку файла. */
  market?: CatalogMarket;
}

/** Дата выгрузки: всё собрано за один вечер, поэтому одна на все записи. */
const COLLECTED_AT = new Date('2026-08-08T00:00:00.000Z');

/**
 * Собирает запись рынка труда из посчитанного по hh.kz.
 *
 * `query` — строка, которую вбивали в поиск. Она попадает в подпись источника не
 * для порядка: на вопрос «откуда цифра» ответом должен быть запрос, который
 * можно повторить при спрашивающем, а не название сайта.
 */
function hh(m: {
  query: string;
  /** Всего вакансий по стране: `area=40`. В базу не идёт, см. шапку файла. */
  vacancies: number;
  /** Из них с указанной зарплатой — знаменатель медианы. */
  withSalary: number;
  /** Бисекция по `only_with_salary=true&salary=X`, линейная интерполяция. */
  medianKzt: number;
  /** `area=160`. */
  almaty: number;
  /** `area=159`. */
  astana: number;
}): CatalogMarket {
  const buckets = [
    { name: 'Алматы', count: m.almaty },
    { name: 'Астана', count: m.astana },
    { name: 'другие регионы', count: m.vacancies - m.almaty - m.astana },
  ];
  return {
    medianSalaryKzt: m.medianKzt,
    // Список отвечает на вопрос «где искать», поэтому порядок значимый: у
    // сварщика первыми идут регионы, у frontend — Алматы. Доли меньше десятой
    // выбрасываем: три вакансии в Астане это не место, куда стоит ехать.
    regions: buckets
      .filter((b) => b.count >= m.vacancies / 10)
      .sort((a, b) => b.count - a.count)
      .map((b) => b.name),
    source:
      `hh.kz, поиск «${m.query}» по РК, 08.08.2026; ` +
      `медиана по ${m.withSalary} вакансиям с указанной зарплатой`,
    collectedAt: COLLECTED_AT,
  };
}

