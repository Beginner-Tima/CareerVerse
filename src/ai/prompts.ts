const dialogueBlock = (dialogue: DialogueTurn[]) =>
  dialogue.length === 0
    ? '(диалога ещё не было)'
    : dialogue
        .map((t, i) => `${i + 1}. Вопрос: ${t.question}\n   Ответ: ${t.answer}`)
        .join('\n');

const profileBlock = (signals: Signal[]) =>
  signals.length === 0
    ? '(профиль пока пуст)'
    : signals
        .map((s) => `- ${s.trait} (${s.weight.toFixed(2)}): ${s.evidence}`)
        .join('\n');

