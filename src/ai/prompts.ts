export const userClarify = (params: {
  dialogue: DialogueTurn[];
  signals: Signal[];
  askedCount: number;
  minQuestions: number;
  maxQuestions: number;
}) => `Диалог целиком:
${dialogueBlock(params.dialogue)}

Накопленный профиль интересов:
${profileBlock(params.signals)}

Это вопрос №${params.askedCount + 1}. Разговор длится столько, сколько нужно:
не меньше ${params.minQuestions} вопросов и не больше ${params.maxQuestions}.
Чем больше уже известно, тем конкретнее должен быть вопрос — от «что тебе
интересно» к «как именно ты бы поступил».`;

