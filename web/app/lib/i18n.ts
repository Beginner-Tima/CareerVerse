/**
 * Язык интерфейса.
 *
 * ВНИМАНИЕ ПЕРЕД СДАЧЕЙ: казахские строки здесь написаны не носителем языка и
 * нуждаются в вычитке. Часть терминов — общепринятые заимствования, часть
 * переведена по смыслу. Всё лежит в одном файле именно поэтому: правка идёт в
 * одном месте, без обхода двенадцати компонентов. Та же оговорка, что и у
 * казахских названий профессий в prisma/catalog.ts.
 *
 * Почему без сегментов `/kk/` в путях, хотя официальный гайд Next советует
 * именно их. Роутинг пришлось бы перекраивать целиком: каждая страница уезжает
 * под `app/[lang]/`, добавляется proxy (в шестнадцатой версии middleware зовут
 * так) с разбором Accept-Language, и все внутренние ссылки начинают требовать
 * префикс. Это правильная дорога для продукта, который живёт годами, и
 * неоправданный риск для ночи перед защитой. Здесь язык — состояние клиента, а
 * не часть адреса.
 *
 * Цена решения названа честно: языком нельзя поделиться ссылкой, и поисковик
 * увидит только русскую версию. Ни то, ни другое на защите не проверяют.
 *
 * Подписка вместо «прочитать в эффекте и положить в состояние» — по тем же
 * причинам, что и в lib/face: чтение localStorage в рендере разошлось бы с
 * серверной разметкой, а setState в теле эффекта запрещён линтером.
 */
import { useSyncExternalStore } from 'react';

export type UiLocale = 'ru' | 'kk';

const KEY = 'careerverse:ui-locale';

const listeners = new Set<() => void>();

export function setUiLocale(locale: UiLocale): void {
  try {
    localStorage.setItem(KEY, locale);
  } catch {
    // Приватный режим — не повод ронять страницу, просто останется русский.
  }
  listeners.forEach((notify) => notify());
}

function subscribe(notify: () => void): () => void {
  listeners.add(notify);
  window.addEventListener('storage', notify);
  return () => {
    listeners.delete(notify);
    window.removeEventListener('storage', notify);
  };
}

function snapshot(): UiLocale {
  try {
    return localStorage.getItem(KEY) === 'kk' ? 'kk' : 'ru';
  } catch {
    return 'ru';
  }
}

/** На сервере языка не знаем: первый кадр русский, дальше уточняется. */
const serverSnapshot = (): UiLocale => 'ru';

export function useUiLocale(): UiLocale {
  return useSyncExternalStore(subscribe, snapshot, serverSnapshot);
}

