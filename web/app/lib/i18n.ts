export type Translate = {
  (key: Key, vars?: Record<string, string | number>): string;
  trait: (code: string) => string;
  locale: UiLocale;
};

/** Подстановка простая, `{имя}`: полноценный ICU здесь не за чем разворачивать. */
function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
}

/**
 * Собираем одним выражением, а не дописыванием полей после создания: компилятор
 * React считает уже созданное значение неизменяемым и на `t.locale = ...`
 * ругается справедливо.
 */
export function useT(): Translate {
  const locale = useUiLocale();

  return Object.assign(
    (key: Key, vars?: Record<string, string | number>) => fill(DICT[locale][key], vars),
    {
      trait: (code: string) =>
        TRAITS[locale][code] ?? TRAITS.ru[code] ?? code.replace(/[-_]/g, ' '),
      locale,
    },
  );
}
